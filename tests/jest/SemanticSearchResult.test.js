'use strict';

const { mount, config } = require( '@vue/test-utils' );
const SearchResult = require( '../../resources/experiments/semanticSearch/components/SearchResult.vue' );

// Interpolated mw.Message objects stringify in MediaWiki.
config.global.mocks.$i18n = ( key, ...args ) => ( {
	text: () => key === 'ellipsis' ? '…' : `${ key }:${ args.join( ',' ) }`,
	toString: () => `${ key }:${ args.join( ',' ) }`
} );

const result = {
	title: 'Example',
	targeturl: '/wiki/Example#section',
	ns: 0,
	timestamp: '2026-10-13T00:00:00Z',
	size: 1024,
	wordcount: 100,
	sectiontitle: 'Answers',
	redirecttitle: 'Alternative title',
	snippet: '<span class="searchmatch">Matched passage</span> and context',
	referencecount: 42
};

test.each( [ false, true ] )( 'preserves links and metadata with semantic=%s', ( semantic ) => {
	const wrapper = mount( SearchResult, { props: { result, semantic } } );
	expect( wrapper.element.tagName ).toBe( 'A' );
	expect( wrapper.attributes( 'href' ) ).toBe( result.targeturl );
	expect( wrapper.attributes( 'title' ) ).toBe( result.title );
	expect( wrapper.text() ).toContain( 'Alternative title' );
	expect( wrapper.text() ).toContain( 'Answers' );
	expect( wrapper.get( '.cdx-card__text__supporting-text' ).text() )
		.toBe( 'readerexperiments-semanticsearch-referencecount:[42]' );
	expect( wrapper.findAll( '.searchmatch' ) ).toHaveLength( 1 );
	expect( wrapper.text() ).toContain( 'and context' );
	expect( wrapper.find( '.cdx-thumbnail__placeholder' ).exists() ).toBe( true );
} );

test( 'keeps the prefixed title and thumbnail without a namespace badge or category statistics', () => {
	const wrapper = mount( SearchResult, {
		props: {
			semantic: true,
			result: Object.assign( {}, result, {
				ns: 14,
				title: 'Category:Example',
				categoryinfo: { size: 3, subcats: 0, files: 3 },
				thumbnail: { source: '/example.jpg' }
			} )
		}
	} );
	expect( wrapper.get( '.cdx-card__text__title' ).text() ).toContain( 'Category:Example' );
	expect( wrapper.find( '.ext-readerExperiments-semanticsearch-result__namespace' ).exists() ).toBe( false );
	expect( wrapper.get( '.cdx-card__text__supporting-text' ).text() )
		.toBe( 'readerexperiments-semanticsearch-referencecount:[42]' );
	expect( wrapper.find( '.cdx-thumbnail__image' ).exists() ).toBe( true );
} );

test( 'omits supporting text when references are unavailable', () => {
	const wrapper = mount( SearchResult, {
		props: { result: { ...result, referencecount: undefined } }
	} );
	expect( wrapper.find( '.cdx-card__text__supporting-text' ).exists() ).toBe( false );
} );

test.each( [
	[ 12, 42, [ 'readerexperiments-semanticsearch-contributorcount:[12]', 'readerexperiments-semanticsearch-referencecount:[42]' ] ],
	[ 12, undefined, [ 'readerexperiments-semanticsearch-contributorcount:[12]' ] ],
	[ 0, 42, [ 'readerexperiments-semanticsearch-referencecount:[42]' ] ]
] )( 'renders contributor count %s and reference count %s as separate metadata values', ( contributorcount, referencecount, expected ) => {
	const wrapper = mount( SearchResult, {
		props: { result: { ...result, contributorcount, referencecount } }
	} );
	// The visual separator is generated by CSS, not part of DOM text.
	const values = wrapper.get( '.cdx-card__text__supporting-text' ).findAll( 'span' );
	expect( values.map( ( value ) => value.text() ) ).toEqual( expected );
} );

test.each( [ false, true ] )( 'uses the shortened passage only for semantic=%s', ( semantic ) => {
	const wrapper = mount( SearchResult, {
		props: {
			semantic,
			result: {
				...result,
				semanticExcerpt: '…<span class="searchmatch">Short answer</span>…'
			}
		}
	} );
	expect( wrapper.find( '.searchmatch' ).text() ).toBe( semantic ? 'Short answer' : 'Matched passage' );
	expect( wrapper.attributes( 'href' ) ).toBe( result.targeturl );
} );

test( 'appends an ellipsis to lexical snippets like Special:Search', () => {
	const wrapper = mount( SearchResult, { props: { result } } );
	expect( wrapper.get( '.cdx-card__text__description' ).text() ).toBe( 'Matched passage and context…' );
} );
